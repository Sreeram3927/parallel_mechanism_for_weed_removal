// The Interpolation Function
inline float getCalibratedPhysicalAngle(char motor_id, float raw_encoder_val) {
  const float* x_array; // The encoder readings (what it thinks it is)
  
  if (motor_id == 'A') x_array = encoder_mA;
  else if (motor_id == 'B') x_array = encoder_mB;
  else if (motor_id == 'C') x_array = encoder_mC;
  else return raw_encoder_val; // Fallback if invalid motor ID

  // 1D Linear Interpolation (Linear Scan)
  for (int i = 0; i < LUT_SIZE - 1; i++) {
    float x0 = x_array[i];
    float x1 = x_array[i+1];
    
    // Check if the raw encoder value falls between these two points
    if ((raw_encoder_val >= x0 && raw_encoder_val <= x1) || 
        (raw_encoder_val >= x1 && raw_encoder_val <= x0)) {
          
      float y0 = physical_angles[i];
      float y1 = physical_angles[i+1];
      
      // Prevent divide by zero if data is completely flat
      if (x1 == x0) return y0;
      
      // The math: y = y0 + (x - x0) * (y1 - y0) / (x1 - x0)
      return y0 + (raw_encoder_val - x0) * (y1 - y0) / (x1 - x0);
    }
  }

  // Fallback: If it's out of bounds, just return the raw reading to prevent the arm from freezing
  return raw_encoder_val; 
}